/**
 * СЛОВО ВЛАДЕЛЬЦА, НАЗВАННОЕ В КОММИТЕ, ОБЯЗАНО НЕСТИ СВОЙ ID СОБЫТИЯ.
 *
 * Правило родилось из разбора 2026-08-14 (класс owner-bafflement, объект
 * commit-stamps-owner-approval-never-given). Коммит c67f4c2 заявил телом
 * «пары, утверждённые Егором 12–13.08 построчно», тогда как дословное слово
 * владельца за тот вечер — ОДНО предложение «по факту я делаю приложение о
 * жизни» (событие 1dc461ab, 2026-08-12T23:33:39Z). Остальная строфа сочинена
 * агентом. Через сутки владелец прочитал её на живом сайте и не узнал:
 * «я по другому говорил кажется, если это на мои слова отсылка».
 *
 * ПОЧЕМУ ИМЕННО ЗДЕСЬ, А НЕ НОВЫМ СТОРОЖЕМ. Такое правило в платформе УЖЕ
 * РАБОТАЕТ и судит класс — узел спеки, назвавший `approvedBy`, проверяется
 * лендом: гейт САМ перечитывает событие в хранилище (существует, from.kind =
 * user, комната из комнат владельца), и выдуманный провенанс роняет ленд
 * своей причиной (`SPEC_RED_FORGED_WORD`, change-exec.ts). Дыра не в правиле,
 * а в ЕГО ОХВАТЕ: та же по смыслу претензия, высказанная ПРОЗОЙ в теле коммита,
 * не проверялась ничем. Здесь достраивается ровно охват — существующим хуком
 * commit-msg (husky + commitlint уже стоят), без второго механизма.
 *
 * СИНТАКСИЧЕСКАЯ ПОЛОВИНА — ТА, ЧТО ЛОВИТ СПЕЦИМЕН. Хранилище из git-хука
 * недостижимо, поэтому здесь проверяется первая половина того же предиката:
 * НАЗВАН ЛИ ПРОВЕНАНС ВООБЩЕ (`no-provenance` — «провенанс не назван вовсе»,
 * OWNER_WORD_REFUSAL_RU). Именно она роняет c67f4c2: тело не называет ничего.
 */

/**
 * ИЗВЕСТНЫЙ ГРУБЫЙ КРАЙ: ПРАВИЛО НЕ ОТЛИЧАЕТ ЗАЯВЛЕНИЕ ОТ ЦИТАТЫ. Сообщение,
 * которое РАЗБИРАЕТ чужую претензию и приводит её дословно, срабатывает так же,
 * как сама претензия. Проверено на себе: коммит, ставящий эти ворота, был ими же
 * отклонён — он цитировал тело специмена. Край оставлен НАРОЧНО: «не считать то,
 * что в кавычках» — готовая лазейка (обернул претензию в кавычки и прошёл), а
 * цена края мала и выход честен: ОПИСАТЬ претензию своими словами вместо
 * дословного воспроизведения либо назвать провенанс трейлером. Тест пиннит это
 * поведение как ожидаемое, чтобы следующий автор не счёл его поломкой.
 */

/**
 * ПРИЧАСТИЕ «УТВЕРЖДЁН», А НЕ СУЩЕСТВИТЕЛЬНОЕ «УТВЕРЖДЕНИЕ». Голый корень
 * /утвержд/ судил бы омоним: на сайте «утверждение» — это ТЕЗИС страницы
 * («У каждого действия есть след»), а не чей-то апрув. На корпусе репозитория
 * широкий корень дал два ложных срабатывания из пяти (f31a14a, 00286e5) — оба
 * про текст на странице, причём f31a14a ещё и ЦИТИРУЕТ владельца дословно, то
 * есть ворота ругались бы ровно на честную работу. Лукахед `(?!и)` отсекает
 * утверждение/утверждения/утверждению, оставляя утверждён/утверждена/
 * утверждены/утверждённые.
 */
const APPROVAL_STEMS = [
  /утвержд[ёе]н(?!и)/i, // утверждён, утверждена, утверждено, утверждены, утверждённые
  /утвердил|утвердит/i,
  /одобр(?!ени)/i, // одобрено, одобрил — но не «одобрение»
  /согласован(?!и)/i, // согласован, согласованного — но не «согласование»
  /\bapproved\b/i,
  /\bsign(?:ed)?[- ]off\b/i,
]

/**
 * ВЛАДЕЛЕЦ ДОЛЖЕН БЫТЬ НАЗВАН. Без этого правило судило бы прилагательное, а не
 * ссылку на его слово: коммит 96cdca0 «утверждённая формула» НЕ заявляет автора
 * апрува и законен — он лишь помечает текст, чей провенанс живёт в другом месте.
 * Специмен же заявляет именно АВТОРИТЕТ: «утверждённые ЕГОРОМ построчно».
 */
/**
 * \b ЗДЕСЬ НЕ ПРИМЕНИМА, И ЭТО НЕ МЕЛОЧЬ. В JS `\b` опирается на ASCII-класс
 * `[A-Za-z0-9_]` (и `/u` этого НЕ меняет), поэтому граница между «Егором» и
 * пробелом не существует: обе стороны — не-словные символы. Первая редакция
 * правила несла `\b` и на полном корпусе репозитория (286 коммитов) дала НОЛЬ
 * срабатываний, пропустив собственный специмен c67f4c2. Ворота были бы зелёными
 * и пустыми. Кириллические корни поэтому идут без хвостовой границы.
 */
const OWNER_TOKENS = [
  /Егор(?:ом|а|у|е)?/i,
  /владельц(?:ем|а|у|е)/i,
  /владелец/i,
  /\bEgor\b/i,
  /\bowner\b/i,
  /его словом?(?![а-яё])/i,
]

/**
 * ПРОВЕНАНС — ЯВНЫЙ ТРЕЙЛЕР, а не любой хекс в теле. Голый 8-значный хекс
 * совпал бы с git-sha, которых в телах полно, и «доказательством» стало бы
 * упоминание соседнего коммита. Форма скопирована с уже живущего рядом
 * `Approved-Change-Id:` — одна грамматика на все ссылки такого рода.
 */
const OWNER_WORD_TRAILER = /^Owner-Word:[ \t]*([0-9a-fA-F][0-9a-fA-F-]{7,})\s*$/m

export const OWNER_WORD_TRAILER_NAME = 'Owner-Word'

/**
 * Разбор сообщения коммита.
 * @param {string} message полный текст сообщения (заголовок + тело + футер)
 * @returns {{claimed: boolean, phrase: string|null, provenance: string|null}}
 */
export function ownerApprovalClaim(message) {
  const text = String(message ?? '')

  // Co-Authored-By и прочие служебные трейлеры не участвуют: «Claude ... approved»
  // в подписи — не претензия на слово владельца.
  const scanned = text
    .split('\n')
    .filter((line) => !/^(?:Co-Authored-By|Signed-off-by|Approved-Change-Id):/i.test(line.trim()))
    .join('\n')

  const approval = APPROVAL_STEMS.find((re) => re.test(scanned))
  const owner = OWNER_TOKENS.find((re) => re.test(scanned))
  const claimed = Boolean(approval && owner)

  const trailer = text.match(OWNER_WORD_TRAILER)
  const provenance = trailer ? trailer[1] : null

  let phrase = null
  if (claimed) {
    // Показать автору ТУ САМУЮ строку, из-за которой встал отказ, — иначе
    // правило звучит как придирка к сообщению целиком.
    phrase =
      scanned
        .split('\n')
        .find((line) => approval.test(line) && owner.test(line))
        ?.trim() ??
      scanned.split('\n').find((line) => approval.test(line))?.trim() ??
      null
  }

  return { claimed, phrase, provenance }
}

/**
 * Вердикт для гейта.
 * @returns {{ok: true} | {ok: false, red: string}}
 */
export function ownerApprovalVerdict(message) {
  const { claimed, phrase, provenance } = ownerApprovalClaim(message)
  if (!claimed || provenance) return { ok: true }

  return {
    ok: false,
    red: [
      'СЛОВО ВЛАДЕЛЬЦА НАЗВАНО, А ПРОВЕНАНС НЕ НАЗВАН ВОВСЕ.',
      '',
      `Сообщение заявляет его апрув: «${phrase ?? '—'}»`,
      'но не называет события, которым он это сказал. Слово агента здесь не стоит',
      'ничего: то же правило уже судит узлы спеки (approvedBy → гейт перечитывает',
      'событие в хранилище), и тело коммита не исключение.',
      '',
      'ДВА ЗАКОННЫХ ВЫХОДА:',
      `  1. Назови id события с его словом трейлером — «${OWNER_WORD_TRAILER_NAME}: <id события>».`,
      '  2. Либо сними саму претензию на апрув: опиши правку как СВОЮ.',
      '',
      'Цена пропуска измерена: c67f4c2 заявил «утверждённые Егором построчно» на',
      'сочинённой строфе, и владелец через сутки не узнал свои слова на живом сайте.',
    ].join('\n'),
  }
}
