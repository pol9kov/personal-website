/**
 * Геометрия секции навыков — ОДИН источник для двух потребителей.
 *
 * Кривая под полосками рисуется заранее скриптом scripts/generate-skill-images.ts
 * в SVG фиксированной высоты, а потом растягивается на контейнер со строками
 * (preserveAspectRatio="none"). Значит скрипт и компонент обязаны считать высоту
 * одинаково — иначе кривая молча уезжает мимо полосок, и ничего не падает.
 *
 * Раньше эти числа лежали в трёх местах: ROW_HEIGHT в компоненте, ROW_HEIGHT и
 * ROW_GAP в скрипте, а сам зазор в разметке задавался классом `gap-4`, о котором
 * скрипт не знал вовсе. Поменяй кто-нибудь `gap-4` на `gap-6` — и рассинхрон
 * появился бы без единой ошибки. Теперь оба читают отсюда, а зазор в разметке
 * задаётся этим же числом, а не классом.
 */

/** Высота строки навыка: название плюс полоска. */
export const SKILL_ROW_HEIGHT = 40;

/** Вертикальный зазор между строками. */
export const SKILL_ROW_GAP = 16;

/**
 * Высота холста кривой для N навыков. Снизу добавляется ещё одна высота строки —
 * место, куда кривая спускается к нулю после последнего навыка.
 */
export function skillChartHeight(count: number): number {
  return count * SKILL_ROW_HEIGHT + (count - 1) * SKILL_ROW_GAP + SKILL_ROW_HEIGHT;
}
